#!/usr/bin/env python3
"""Reuse exact original FP32 step equations with already queried parameters."""
import argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'include/carbon/electron_batch_original.hpp'


def render():
    src=(ROOT/'include/carbon/electron_voxel_cache.hpp').read_text()
    src=src[src.index('template<class Uniform,class Model>inline ChargedStep transport_step_face('):src.index('template<class Uniform,class Tally,class Score=NoExpectedScore>')].strip()
    src=src.replace('transport_step_face(', 'original_prepared(',1)
    src=src.replace('const std::array<float,2>& hard_majorant,Uniform& uniform,', 'const std::array<float,2>& hard_majorant,const ChargedParameters& p,Uniform& uniform,',1)
    start=src.index('    #ifdef CARBON_ELECTRON_CERTIFIED_RATES')
    end=src.index('    if(!p.valid)',start)
    assert 'charged_parameters_certified(model,energy)' in src[start:end]
    src=src[:start]+src[end:]
    return ('#pragma once\n// Generated by scripts/generate_electron_batch_original.py.\n'
            '// Research-only original step; equations and RNG order unchanged.\n'
            '#include "carbon/electron_voxel_cache.hpp"\n'
            'namespace carbon::electron_fp32::elastic_batch_reference {\n'+src+'\n}\n')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();text=render()
    if a.check:
        if not TARGET.exists() or TARGET.read_text()!=text:raise SystemExit('Generated batch original is stale')
    else:TARGET.write_text(text)
