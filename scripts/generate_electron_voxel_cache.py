#!/usr/bin/env python3
"""Generate an exact-physics cached wrapper from the maintained FP32 equations."""
import argparse
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'include/carbon/electron_fp32.hpp'
TARGET=ROOT/'include/carbon/electron_voxel_cache.hpp'


def render():
    src=SOURCE.read_text()
    step=src[src.index('template<class Uniform,class Model>inline ChargedStep transport_charged_step('):src.index('// electron_charged_packet.hpp')].strip()
    packet=src[src.index('template<class Uniform,class Tally,class Score=NoExpectedScore>\ninline ElectronEnergyPacket transport_independent_charged_packet('):src.index('// photon_optical_transport.hpp')].strip()
    assert step.count('const auto face=next_charged_face(geometry,start,direction);')==1
    assert 'float maximum_step=.05f,float mean_loss_fraction=.005f' in step, 'revalidate cached geometry guard after step-policy changes'
    step=step.replace('transport_charged_step(', 'transport_step_face(',1)
    step=step.replace('const ElectronCtGeometry& geometry,Position start','const ChargedFace& face,Position start',1)
    step=step.replace('const auto face=next_charged_face(geometry,start,direction);','')
    packet=packet.replace('transport_independent_charged_packet(', 'transport_packet(',1)
    packet=packet.replace('const ElectronCtGeometry& geometry,Uniform& uniform,Tally& tally,', 'const ElectronCtGeometry& geometry,Cache& cache,Uniform& uniform,Tally& tally,',1)
    packet=packet.replace('const auto face=next_charged_face(geometry,packet.cursor.position,packet.cursor.direction);', 'const auto face=cached_face(geometry,packet.cursor.position,packet.cursor.direction,cache);',1)
    packet=packet.replace('const auto bracket=charged_density_bracket(bank,face.section,face.density);', 'const bool material_valid=prepare_material(bank,geometry,face,cache);',1).replace('if(!bracket.valid){','if(!material_valid){',1)
    packet=packet.replace('const auto model=charged_density_model(bank.nodes+bracket.low,bank.nodes+bracket.high,face.density);','const auto& model=cache.model;',1)
    packet=packet.replace('transport_charged_step(model,geometry,','transport_step_face(model,face,',1)
    packet=packet.replace('charged_density_majorant(bank,bracket,face.density),uniform','cache.majorant,uniform',1)
    preamble='''#pragma once
// Generated by scripts/generate_electron_voxel_cache.py. Physics and RNG order
// are copied from the authoritative FP32 step and packet implementations.
#include "carbon/electron_fp32.hpp"
namespace carbon::electron_fp32::voxel_cache_research {
// One immutable geometry and bank per cache lifetime. Reset before a new task
// or before changing either geometry/bank. No energy-dependent values cached.
struct Cache {
    bool valid{};
    std::uint64_t voxel{};
    Position lower{},upper{};
    ChargedDensityModel model{};
    std::array<float,2> majorant{};
#ifdef CARBON_ELECTRON_VOXEL_CACHE_DIAGNOSTICS
    unsigned face_hits{},material_hits{},refreshes{};
#endif
};
inline ChargedFace cached_face(const ElectronCtGeometry& geometry,Position start,
    std::array<float,3> direction,Cache& cache) {
    if(cache.valid){
        // The original direction contract allows norm-squared error<=32eps.
        // Use a larger margin for the maximum absolute component and rounded
        // ray division. A strict interior check excludes all exact faces.
        constexpr float guard=.05f*(1+64*std::numeric_limits<float>::epsilon());
        bool safe=true;float norm=0;
        for(unsigned k=0;k<3;++k){
            safe=safe&&std::isfinite(start[k])&&std::isfinite(direction[k])
                &&start[k]-cache.lower[k]>guard&&cache.upper[k]-start[k]>guard;
            norm+=direction[k]*direction[k];
        }
        if(safe&&std::abs(norm-1)<=32*std::numeric_limits<float>::epsilon()){
            ChargedFace out;out.valid=true;out.distance=std::numeric_limits<float>::infinity();
            out.position=start;out.voxel=cache.voxel;out.section=cache.model.section;out.density=cache.model.density;
#ifdef CARBON_ELECTRON_VOXEL_CACHE_DIAGNOSTICS
            ++cache.face_hits;
#endif
            return out;
        }
    }
    return next_charged_face(geometry,start,direction);
}
inline bool prepare_material(ChargedBankView bank,const ElectronCtGeometry& geometry,
    const ChargedFace& face,Cache& cache){
    if(cache.valid&&face.voxel==cache.voxel){
#ifdef CARBON_ELECTRON_VOXEL_CACHE_DIAGNOSTICS
        ++cache.material_hits;
#endif
        return true;
    }
    cache.valid=false;
    const auto bracket=charged_density_bracket(bank,face.section,face.density);
    if(!bracket.valid)return false;
    cache.model=charged_density_model(bank.nodes+bracket.low,bank.nodes+bracket.high,face.density);
    cache.majorant=charged_density_majorant(bank,bracket,face.density);
    cache.voxel=face.voxel;
    auto remainder=face.voxel;
    for(unsigned k=0;k<3;++k){
        const auto cell=remainder%geometry.bins[k];remainder/=geometry.bins[k];
        cache.lower[k]=geometry.origin[k]+cell*geometry.spacing[k];
        cache.upper[k]=geometry.origin[k]+(cell+1)*geometry.spacing[k];
    }
    cache.valid=true;
#ifdef CARBON_ELECTRON_VOXEL_CACHE_DIAGNOSTICS
    ++cache.refreshes;
#endif
    return true;
}
'''
    return preamble+step+'\n\n'+packet+'\n} // namespace carbon::electron_fp32::voxel_cache_research\n'


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();text=render()
    if a.check:
        if not TARGET.exists() or TARGET.read_text()!=text:raise SystemExit('stale cached wrapper')
    else:TARGET.write_text(text)


if __name__=='__main__':main()
