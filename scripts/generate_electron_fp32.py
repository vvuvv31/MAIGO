def single(s):
    # Do not change strings/comments. Explicit float literals prevent silent
    # promotion back to double in expressions and standard-library overloads.
    token = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\bdouble\b|(?<![\w.])(?:\d+\.\d*|\.\d+|\d+[eE][+-]?\d+)(?:[eE][+-]?\d+)?(?![\w.])')
    def cv(m):
        x=m.group()
        if x.startswith(('//','/*','"')):return x
        return 'float' if x=='double' else x+'f'
    return token.sub(cv,s)

