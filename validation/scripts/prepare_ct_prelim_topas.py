def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--spots",
        nargs="+",
        type=Path,
        default=[Path("ct/topas/spots_c_01.txt"), Path("ct/topas/spots_c_02.txt")],
    )
    ap.add_argument("--weights", type=Path, default=Path("ct/spotWeight.csv"))
    ap.add_argument("--outdir", type=Path, default=Path("ct/topas/mc_ref"))
    ap.add_argument("--single-histories", type=int, default=50000)
    ap.add_argument("--layer-spots", type=int, default=20)
    ap.add_argument("--layer-histories-each", type=int, default=5000)
    ap.add_argument("--threads", type=int, default=40)
    ap.add_argument("--dicom-directory", default="../../dicom")
    args = ap.parse_args()

    ch = load_combined(args.spots)
    n = len(ch[0])
    weights = []
    with args.weights.open(encoding="utf-8-sig") as handle:
        for row in csv.reader(handle):
            if not row:
                continue
            weights.append(float(row[0]))
    if len(weights) != n:
        raise SystemExit(f"weights {len(weights)} != spots {n}")

    energies_MeVu = [e / 12.0 for e in ch[2]]
    # Highest-weight 235 MeV/u spot
    idx_235 = [i for i in range(n) if abs(energies_MeVu[i] - 235.0) < 0.1]
    if not idx_235:
        raise SystemExit("No 235 MeV/u spots found")
    single = max(idx_235, key=lambda i: weights[i])
    print(
        f"single spot index={single} weight={weights[single]:.4g} "
        f"E={energies_MeVu[single]:.1f} MeV/u tx={ch[5][single]:.4g} tz={ch[6][single]:.4g}"
    )

    idx_220 = [i for i in range(n) if abs(energies_MeVu[i] - 220.0) < 0.1]
    if len(idx_220) < args.layer_spots:
        raise SystemExit(f"Only {len(idx_220)} spots at 220 MeV/u")
    layer = sorted(idx_220, key=lambda i: -weights[i])[: args.layer_spots]
    print(f"layer_eq {len(layer)} spots at 220 MeV/u, top weight={weights[layer[0]]:.4g}")

    out = args.outdir
    write_spots(
        out / "spots_single.txt",
        ch,
        [single],
        [args.single_histories],
    )
    write_spots(
        out / "spots_layer_eq.txt",
        ch,
        layer,
        [args.layer_histories_each] * len(layer),
    )
    write_run(
        out / "run_single_spot.txt",
        "spots_single.txt",
        timeline_end_ms=1.0,
        n_times=1,
        tag="single",
        threads=args.threads,
        dicom_directory=args.dicom_directory,
    )
    write_run(
        out / "run_layer_eq.txt",
        "spots_layer_eq.txt",
        timeline_end_ms=float(len(layer)),
        n_times=len(layer),
        tag="layer_eq",
        threads=args.threads,
        dicom_directory=args.dicom_directory,
    )

    # GPU-side spot files (same content) for prelim configs already point here.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
