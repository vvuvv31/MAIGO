#!/usr/bin/env python3
"""Build CT prelim TOPAS spots + run decks from the optimized plan files.

Outputs under ct/topas/mc_ref/:
  spots_single.txt      highest-weight 235 MeV/u spot, 50k histories
  spots_layer_eq.txt    20 highest-weight 220 MeV/u spots, equal 5k each
  run_single_spot.txt   DoseToMedium on Patient (417×505×35) CSV
  run_layer_eq.txt

Also writes a rebin helper for TOPAS CSV → compare grid (104×126×35 @ 2 mm).
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path


def parse_channels(path: Path) -> dict[int, list[float]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    channels: dict[int, list[float]] = {}
    for line in lines:
        m = re.match(
            r"[diu]v:Tf/Scatterer1/L(\d+)/Values\s*=\s*(.*)", line.strip()
        )
        if not m:
            continue
        lab = int(m.group(1))
        body = re.sub(r"\b(MeV|mm|deg|ms)\b", "", m.group(2))
        parts = body.split()
        n = int(float(parts[0]))
        channels[lab] = [float(x) for x in parts[1 : n + 1]]
    if 0 not in channels:
        raise SystemExit(f"No L0 Values in {path}")
    return channels


def load_combined(spots_paths: list[Path]) -> dict[int, list[float]]:
    combined: dict[int, list[float]] = {}
    for path in spots_paths:
        ch = parse_channels(path)
        for lab, vals in ch.items():
            combined.setdefault(lab, []).extend(vals)
    n = len(combined[0])
    for lab, vals in combined.items():
        if len(vals) != n:
            raise SystemExit(f"Channel L{lab} length {len(vals)} != {n}")
    return combined


def write_spots(
    out: Path,
    channels: dict[int, list[float]],
    indices: list[int],
    histories: list[int],
) -> None:
    n = len(indices)
    out.parent.mkdir(parents=True, exist_ok=True)
    type_for = {
        0: "iv",
        1: "dv",
        2: "dv",
        3: "uv",
        4: "iv",
        5: "dv",
        6: "dv",
        7: "dv",
        8: "dv",
        9: "dv",
        10: "uv",
        11: "uv",
        12: "dv",
        13: "uv",
        14: "uv",
    }
    units = {
        1: " MeV",
        2: " MeV",
        5: " mm",
        6: " mm",
        7: " deg",
        8: " deg",
        9: " mm",
        12: " mm",
    }
    lines: list[str] = []
    for lab in range(15):
        lines.append(f's:Tf/Scatterer1/L{lab}/Function = "Step"')
    lines.append("")
    times = " ".join(str(float(i + 1)) for i in range(n))
    lines.append(f"dv:Tf/Scatterer1/L0/Times = {n} {times} ms")
    for lab in range(1, 15):
        lines.append(f"dv:Tf/Scatterer1/L{lab}/Times   = Tf/Scatterer1/L0/Times ms")
    lines.append("")
    for lab in range(15):
        typ = type_for[lab]
        if lab == 0:
            vals = [float(i + 1) for i in range(n)]
        elif lab == 4:
            vals = [float(h) for h in histories]
        else:
            vals = [channels[lab][i] for i in indices]
        if lab in (0, 4):
            body = " ".join(str(int(v)) for v in vals)
        else:
            body = " ".join(f"{v:.6g}" for v in vals)
        unit = units.get(lab, "")
        lines.append(f"{typ}:Tf/Scatterer1/L{lab}/Values = {n} {body}{unit}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({n} spots, histories={histories[0] if len(set(histories))==1 else 'mixed'})")


